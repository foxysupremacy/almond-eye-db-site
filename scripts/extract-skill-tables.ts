// Small master.mdb-derived skill tables used by the race-impact model and the
// rankings candidate list. Called from extract-mdb.ts (build:data) and runnable
// on its own, so these outputs can be refreshed without regenerating the rest:
//
//   UMAMUSUME_MDB_PATH=... node --experimental-strip-types scripts/extract-skill-tables.ts
//
// Outputs:
//   1. lib/race-impact/generated/skill-level-coef.ts (skill_level_value)
//      A TS module, not JSON: lib/race-impact is part of the rankings worker
//      graph, which must never import JSON (lib/rankings/purity.test.ts).
//   2. lib/data/generated/character-evolutions.json (skill_upgrade_description)
//      MERGE: existing entries keep their names/descriptions; their display
//      condition1 (and iconId, when the mdb has one) is refreshed from the mdb.
//      Rows missing from the file (new costumes, a second option in a slot,
//      rank-7 slots) are added.
import fs from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";
import { loadEnv } from "./env.ts";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const SITE_ROOT = path.resolve(__dirname, "..");

const LEVEL_COEF_PATH = path.resolve(SITE_ROOT, "lib/race-impact/generated/skill-level-coef.ts");
const EVOLUTIONS_PATH = path.resolve(SITE_ROOT, "lib/data/generated/character-evolutions.json");
const SKILLS_PATH = path.resolve(SITE_ROOT, "lib/data/generated/skills.json");

/** Unique skill levels exposed by the UI (lib/race-impact/unique-level.ts MAX_UNIQUE_LEVEL). */
const MAX_LEVEL = 6;

type Row = Record<string, unknown>;

/** Per-ability-type level coefficients (ten-thousandths) for levels 1..MAX_LEVEL. */
export function extractSkillLevelCoef(db: DatabaseSync): void {
  // Only ability types that skills actually use.
  const usedTypes = new Set<number>();
  const cols: string[] = [];
  for (const g of [1, 2]) for (const e of [1, 2, 3]) cols.push(`ability_type_${g}_${e}`);
  for (const row of db.prepare(`SELECT ${cols.join(", ")} FROM skill_data`).all() as Row[]) {
    for (const c of cols) { const t = Number(row[c]); if (t > 0) usedTypes.add(t); }
  }
  // Every unique (rarity 3-5) effect uses the default level scaling (ability_value_level_usage 1).
  const usage = db.prepare(
    "SELECT ability_value_level_usage_1_1 a, ability_value_level_usage_1_2 b, ability_value_level_usage_1_3 c, " +
    "ability_value_level_usage_2_1 d, ability_value_level_usage_2_2 e, ability_value_level_usage_2_3 f, " +
    "ability_type_1_1 ta, ability_type_1_2 tb, ability_type_1_3 tc, ability_type_2_1 td, ability_type_2_2 te, ability_type_2_3 tf " +
    "FROM skill_data WHERE rarity BETWEEN 3 AND 5",
  ).all() as Row[];
  let nonDefault = 0;
  for (const r of usage) {
    for (const [u, t] of [["a", "ta"], ["b", "tb"], ["c", "tc"], ["d", "td"], ["e", "te"], ["f", "tf"]]) {
      if (Number(r[t]) > 0 && Number(r[u]) !== 1) nonDefault++;
    }
  }
  if (nonDefault) console.warn(`skill-level-coef: ${nonDefault} unique effects use a non-default level usage (not modeled)`);

  const table = new Map<number, number[]>();
  for (const row of db.prepare(
    "SELECT ability_type, level, float_ability_value_coef FROM skill_level_value WHERE level <= ? ORDER BY ability_type, level",
  ).all(MAX_LEVEL) as Row[]) {
    const type = Number(row.ability_type);
    if (!usedTypes.has(type)) continue;
    const list = table.get(type) ?? [];
    list[Number(row.level) - 1] = Number(row.float_ability_value_coef);
    table.set(type, list);
  }
  const lines = [...table.entries()]
    .filter(([, coef]) => coef.length === MAX_LEVEL && coef.every((v) => Number.isFinite(v)))
    .sort(([a], [b]) => a - b)
    .map(([type, coef]) => `  ${type}: [${coef.join(", ")}],`);
  const src = [
    "// GENERATED by scripts/extract-skill-tables.ts from master.mdb `skill_level_value` — do not edit.",
    "// float_ability_value_coef per ability type for unique skill levels 1..6, in ten-thousandths",
    "// (10000 = x1.0). Only ability types used by skill_data are included.",
    "export const SKILL_LEVEL_COEF: Readonly<Record<number, readonly number[]>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
  fs.mkdirSync(path.dirname(LEVEL_COEF_PATH), { recursive: true });
  fs.writeFileSync(LEVEL_COEF_PATH, src);
  console.log(`Skill level coefficients: ${lines.length} ability types → ${LEVEL_COEF_PATH}`);
}

// Same tagging rule as extract-collection-data.ts.
function detectEvolBranchTag(condStr: string): string | null {
  if (condStr.includes("distance_type==1")) return "Short";
  if (condStr.includes("distance_type==2")) return "Mile";
  if (condStr.includes("distance_type==3")) return "Medium";
  if (condStr.includes("distance_type==4")) return "Long";
  if (condStr.includes("ground_type==1")) return "Turf";
  if (condStr.includes("ground_type==2")) return "Dirt";
  if (condStr.includes("running_style==1")) return "Runner";
  if (condStr.includes("running_style==2")) return "Leader";
  if (condStr.includes("running_style==3")) return "Betweener";
  if (condStr.includes("running_style==4")) return "Chaser";
  return null;
}

/**
 * Merges skill_upgrade_description into character-evolutions.json. Rank 3 = evolution slot 1, rank 5 = slot 2,
 * rank 7 = slot 3. Existing entries keep their names and descriptions (including hachimi translations); their
 * display fields are refreshed from skill_data: `condition1` always, `iconId` only when the mdb icon_id is
 * non-zero (newer rows ship 0). Each patched card's list follows the mdb order (rank, skill id). New entries take
 * names from skills.json.
 */
export function patchCharacterEvolutions(db: DatabaseSync): void {
  const rawText = fs.readFileSync(EVOLUTIONS_PATH, "utf8");
  const eol = rawText.includes("\r\n") ? "\r\n" : "\n";
  const existing = JSON.parse(rawText) as Record<string, Row[]>;
  const skills = JSON.parse(fs.readFileSync(SKILLS_PATH, "utf8")) as Row[];
  const skillById = new Map(skills.map((s) => [Number(s.id), s]));

  const skillData = new Map<number, Row>();
  for (const s of db.prepare("SELECT id, icon_id, condition_1, precondition_1 FROM skill_data").all() as Row[]) {
    skillData.set(Number(s.id), s);
  }
  // card id -> need_rank -> gold skill (the base an evolution upgrades).
  const baseByCardRank = new Map<number, Map<number, number>>();
  for (const r of db.prepare(
    "SELECT c.id card_id, a.need_rank, a.skill_id FROM card_data c JOIN available_skill_set a ON a.available_skill_set_id = c.available_skill_set_id WHERE a.need_rank > 0",
  ).all() as Row[]) {
    const m = baseByCardRank.get(Number(r.card_id)) ?? new Map<number, number>();
    m.set(Number(r.need_rank), Number(r.skill_id));
    baseByCardRank.set(Number(r.card_id), m);
  }

  const byCard = new Map<number, { rank: number; skillId: number }[]>();
  for (const u of db.prepare("SELECT card_id, rank, skill_id FROM skill_upgrade_description ORDER BY card_id, rank, skill_id").all() as Row[]) {
    const list = byCard.get(Number(u.card_id)) ?? [];
    list.push({ rank: Number(u.rank), skillId: Number(u.skill_id) });
    byCard.set(Number(u.card_id), list);
  }

  // Refresh display fields on existing entries (stale text otherwise survives mdb condition changes).
  const refreshed: string[] = [];
  for (const [cardId, entries] of Object.entries(existing)) {
    for (const e of entries) {
      const sData = skillData.get(Number(e.skillId));
      if (!sData) continue;
      const condition1 = typeof sData.condition_1 === "string" ? sData.condition_1.trim() : "";
      const changes: string[] = [];
      if (condition1 && e.condition1 !== condition1) { e.condition1 = condition1; changes.push("condition1"); }
      if (!condition1 && "condition1" in e) { delete e.condition1; changes.push("condition1"); }
      const icon = Number(sData.icon_id) || 0;
      if (icon && e.iconId !== icon) { e.iconId = icon; changes.push("iconId"); }
      if (changes.length) refreshed.push(`${cardId}:${e.skillId} (${changes.join("+")})`);
    }
  }

  const added: string[] = [];
  for (const [cardId, rows] of byCard) {
    const current = existing[String(cardId)] ?? [];
    if (rows.every((r) => current.some((e) => Number(e.skillId) === r.skillId))) continue;
    const merged: Row[] = [];
    for (const r of rows) {
      const kept = current.find((e) => Number(e.skillId) === r.skillId);
      if (kept) { merged.push(kept); continue; }
      const sData = skillData.get(r.skillId);
      const skill = skillById.get(r.skillId);
      const branchTag = detectEvolBranchTag(sData ? `${sData.condition_1 || ""} ${sData.precondition_1 || ""}` : "");
      const entry: Row = {
        rank: r.rank,
        baseSkillId: baseByCardRank.get(cardId)?.get(r.rank) ?? 0,
        skillId: r.skillId,
        nameEn: (skill?.nameEn as string) || (skill?.nameJp as string) || `Skill ${r.skillId}`,
        nameJp: (skill?.nameJp as string) || "",
        descEn: (skill?.descEn as string) || (skill?.descJp as string) || "",
        descJp: (skill?.descJp as string) || "",
        iconId: sData?.icon_id ? Number(sData.icon_id) : typeof skill?.iconId === "number" ? skill.iconId : null,
      };
      if (branchTag) entry.branchTag = branchTag;
      if (sData?.condition_1) entry.condition1 = sData.condition_1;
      merged.push(entry);
      added.push(`${cardId}:${r.rank}:${r.skillId}`);
    }
    // Keep any file-only entries (none expected) after the mdb rows.
    for (const e of current) if (!merged.includes(e)) merged.push(e);
    existing[String(cardId)] = merged;
  }
  if (!added.length && !refreshed.length) {
    console.log("character-evolutions.json already matches skill_upgrade_description");
    return;
  }
  fs.writeFileSync(EVOLUTIONS_PATH, JSON.stringify(existing, null, 2).replace(/\n/g, eol));
  if (added.length) console.log(`character-evolutions.json: +${added.length} entries from mdb (${added.join(", ")})`);
  if (refreshed.length) console.log(`character-evolutions.json: refreshed ${refreshed.length} entries (${refreshed.join(", ")})`);
}

function openMdb(): DatabaseSync {
  loadEnv();
  const mdbPath = process.env.UMAMUSUME_MDB_PATH || "";
  if (!mdbPath || !fs.existsSync(mdbPath)) {
    console.error(`Error: master.mdb not found (UMAMUSUME_MDB_PATH=${mdbPath || "<unset>"})`);
    process.exit(1);
  }
  return new DatabaseSync(mdbPath, { readOnly: true });
}

if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  const db = openMdb();
  extractSkillLevelCoef(db);
  patchCharacterEvolutions(db);
  db.close();
}
